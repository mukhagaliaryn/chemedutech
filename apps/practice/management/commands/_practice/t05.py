def reaction(label, answer, kind):
    """5 points: products and coefficients (4) and the type of the reaction (1)."""
    return [
        equation(label, "Өнімдерін жазып, коэффициенттерін қойыңыз.", answer, points=4),
        choice(f"{label} · реакция түрі", "Реакцияның түрін таңдаңыз.", TYPES, kind),
    ]



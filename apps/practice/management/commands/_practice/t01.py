CHANGES = ["0 → +2", "+1 → 0", "0 → −2", "+2 → 0", "0 → +1", "−1 → −2", "−1 → 0", "0 → −1"]


def redox(reaction, oxidant, reductant, options, changes):
    """Three fields per reaction (4 points): the oxidising agent, the reducing agent, oxidation-state changes."""
    distractors = [c for c in CHANGES if c not in changes.values()][:3]
    return [
        (f"{reaction} · тотықтырғыш", "Тотықтырғышты таңдаңыз.", "choice", 1,
         {"options": options, "correct": [oxidant]}, ""),
        (f"{reaction} · тотықсыздандырғыш", "Тотықсыздандырғышты таңдаңыз.", "choice", 1,
         {"options": options, "correct": [reductant]}, ""),
        (f"{reaction} · тотығу дәрежелері", "Әр элемент үшін тотығу дәрежесінің өзгерісін сәйкестендіріңіз.",
         "matching", 2, {"pairs": changes, "distractors": distractors}, ""),
    ]  # fmt: skip



def trim(text: str, quality: float) -> str:
    """A weaker student writes less: the first sentence only below 0.6, the first two below 0.8."""
    sentences = [s for s in re.split(r"(?<=[.!?;])\s+", text.strip()) if s]
    if quality < 0.6:
        sentences = sentences[:1]
    elif quality < 0.8:
        sentences = sentences[:2]
    return " ".join(sentences)


def p(text: str) -> str:
    return f"<p>{text}</p>"


